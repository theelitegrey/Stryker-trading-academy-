/* Home hero, preview variation C ("Dashboard"). Preview page only.
   A crosshair walks the illustrative chart: call wall -> zero gamma -> POC
   -> entry zone, and the matching readout cell lights up. Transforms and
   opacity only. Paused off-screen and in hidden tabs. Reduced motion gets
   the finished static chart. No libraries. */
(function () {
  'use strict';
  var card = document.getElementById('hcc');
  if (!card) return;
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (reduce) return;   // markup is already the finished chart

  // [x, y] in SVG user units, generated by tools/storyboards/home-combo-c-gen.py
  var STOPS = [[132, 54], [388, 103], [336, 99], [202, 103]];
  var STEP_MS = 2200, START_MS = 3700;

  var cx = card.querySelector('.hcc-cur-x');
  var cy = card.querySelector('.hcc-cur-y');
  var cd = card.querySelector('.hcc-cur-d');
  var cells = card.querySelectorAll('.hcc-ro');
  var levels = card.querySelectorAll('.hcc-svg [data-k]');
  var step = -1, timer = 0, visible = true, started = false;

  card.classList.add('pre');
  requestAnimationFrame(function () {
    requestAnimationFrame(function () { card.classList.remove('pre'); card.classList.add('go'); });
  });

  function show(k) {
    var p = STOPS[k];
    cx.style.transform = 'translate(' + p[0] + 'px,0)';
    cy.style.transform = 'translate(0,' + p[1] + 'px)';
    cd.style.transform = 'translate(' + p[0] + 'px,' + p[1] + 'px)';
    for (var i = 0; i < cells.length; i++) cells[i].classList.toggle('on', +cells[i].getAttribute('data-k') === k);
    for (var j = 0; j < levels.length; j++) {
      var lk = levels[j].getAttribute('data-k');
      // the confluence band stays lit once reached; the active level glows
      levels[j].classList.toggle('on', lk === String(k) || (lk === '3' && k === 3));
    }
  }
  function tick() {
    step = (step + 1) % STOPS.length;
    show(step);
    timer = setTimeout(tick, step === 3 ? STEP_MS * 1.6 : STEP_MS);
  }
  function gate() {
    var run = visible && !document.hidden;
    card.classList.toggle('paused', !run);
    clearTimeout(timer); timer = 0;
    if (!run) return;
    if (!started) {
      started = true;
      // park the crosshair on the first stop without a sweep from the origin
      [cx, cy, cd].forEach(function (el) { el.style.transition = 'none'; });
      step = -1; tick();
      requestAnimationFrame(function () {
        requestAnimationFrame(function () { [cx, cy, cd].forEach(function (el) { el.style.transition = ''; }); });
      });
      return;
    }
    timer = setTimeout(tick, STEP_MS);
  }
  setTimeout(function () {
    card.classList.add('run');
    gate();
  }, START_MS);

  if ('IntersectionObserver' in window) {
    new IntersectionObserver(function (es) {
      visible = es[0].isIntersecting;
      if (card.classList.contains('run')) gate();
      else card.classList.toggle('paused', !visible);
    }, { threshold: 0 }).observe(card);
  }
  document.addEventListener('visibilitychange', function () { if (card.classList.contains('run')) gate(); });

  // Subtle parallax tilt, fine pointers only. One rAF per pointer frame.
  if (window.matchMedia('(hover: hover) and (pointer: fine)').matches) {
    var wrap = card.querySelector('.hcc-wrap'), raf = 0, tx = 0, ty = 0;
    card.addEventListener('pointermove', function (e) {
      var r = card.getBoundingClientRect();
      tx = (e.clientX - r.left) / r.width - 0.5;
      ty = (e.clientY - r.top) / r.height - 0.5;
      if (!raf) raf = requestAnimationFrame(function () {
        raf = 0;
        wrap.style.transform = 'perspective(1000px) rotateX(' + (-ty * 4).toFixed(2) + 'deg) rotateY(' + (tx * 5).toFixed(2) + 'deg)';
      });
    });
    card.addEventListener('pointerleave', function () {
      wrap.style.transition = 'transform .5s ease';
      wrap.style.transform = '';
      setTimeout(function () { wrap.style.transition = ''; }, 500);
    });
  }
})();
