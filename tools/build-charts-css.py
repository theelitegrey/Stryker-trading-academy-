#!/usr/bin/env python3
"""Build assets/style-charts.css: the rules of assets/style.css the Charts page can use.

PHONE SPEED (Owner "optimize for phone", 2026-10-26). style.css is one 570 KB sheet shared by every page;
on a phone the Charts page spends ~0.5 s matching its ~10k rules against the chart DOM (style recalcs while
the chart mounts). charts.html loads this generated subset instead. style.css stays the ONE source:
edit style.css, then run this script (check.py fails when the subset is out of date).

Which rules are dropped: only rules whose every selector needs a class or id that the Charts page can never
produce. The "can produce" set is every word in charts.html and in every script the page can load (its
<script src>s, their static + dynamic imports, recursively, plus both Vela engines and zag). A class built
at run time from a prefix ('stkgl-' + name) counts as present when the prefix appears as a string end.
Selectors inside :not() / :is() / :where() / :has() and attribute selectors never cause a drop. @font-face,
@keyframes, @property, :root and element-only rules are always kept. Order is preserved, so the cascade
is the same as style.css for everything kept.

  python3 tools/build-charts-css.py          # write assets/style-charts.css
  python3 tools/build-charts-css.py --check  # exit 1 if it would change (check.py runs this)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'style.css')
OUT = os.path.join(ROOT, 'assets', 'style-charts.css')
PAGE = os.path.join(ROOT, 'charts.html')
HEADER = ('/* GENERATED by tools/build-charts-css.py from assets/style.css for charts.html. DO NOT EDIT:\n'
          '   edit assets/style.css and re-run the script. Rules the Charts page can never match are left out. */\n')

# whole folders the page can load (the engines are picked by an import map at run time)
EXTRA_DIRS = ['assets/vendor/vela-0.9.0-s4', 'assets/vendor/vela-0.6.17-s3', 'assets/vendor/zag-1.42.0']


def read(p):
    with open(p, encoding='utf-8', errors='replace') as f:
        return f.read()


def corpus_files():
    seen, todo = set(), []
    html = read(PAGE)
    for m in re.finditer(r'''(?:src|href)\s*=\s*["']/?(assets/[^"'?#]+\.(?:js|mjs|html))''', html):
        todo.append(os.path.normpath(os.path.join(ROOT, m.group(1))))
    # module paths named anywhere in the page (import map, modulepreload, inline imports)
    for m in re.finditer(r'''["'`]/?(assets/[\w./-]+\.m?js)''', html):
        todo.append(os.path.normpath(os.path.join(ROOT, m.group(1))))
    for d in EXTRA_DIRS:
        for dp, _, fs in os.walk(os.path.join(ROOT, d)):
            for f in fs:
                if f.endswith(('.js', '.mjs')):
                    todo.append(os.path.join(dp, f))
    while todo:
        f = todo.pop()
        if f in seen or not os.path.isfile(f):
            continue
        seen.add(f)
        s = read(f)
        base = os.path.dirname(f)
        # ./x.js, ../x.js, /assets/x.js, assets/x.js in imports, dynamic imports, script injection, fetch
        for m in re.finditer(r'''["'`]((?:\.{1,2}/|/assets/|assets/)[\w./-]+\.(?:m?js|html))''', s):
            p = m.group(1)
            if p.startswith('/assets/') or p.startswith('assets/'):
                q = os.path.normpath(os.path.join(ROOT, p.lstrip('/')))
            else:
                q = os.path.normpath(os.path.join(base, p))
            todo.append(q)
    return sorted(seen)


def strip_comments(css):
    out, i, n = [], 0, len(css)
    while i < n:
        if css.startswith('/*', i):
            j = css.find('*/', i + 2)
            i = n if j < 0 else j + 2
            continue
        c = css[i]
        if c in '"\'':
            j = i + 1
            while j < n and css[j] != c:
                j += 2 if css[j] == '\\' else 1
            out.append(css[i:j + 1]); i = j + 1
            continue
        out.append(c); i += 1
    return ''.join(out)


def blocks(css):
    """Split top-level CSS into (prelude, body) pairs; body None for statements ending in ';'."""
    res, i, n = [], 0, len(css)
    while i < n:
        while i < n and css[i] in ' \t\r\n':
            i += 1
        if i >= n:
            break
        j, depth, start, pre_end = i, 0, i, i
        while j < n:
            c = css[j]
            if c in '"\'':
                k = j + 1
                while k < n and css[k] != c:
                    k += 2 if css[k] == '\\' else 1
                j = k + 1
                continue
            if c == ';' and depth == 0:
                res.append((css[start:j].strip(), None)); j += 1; break
            if c == '{':
                if depth == 0:
                    pre_end = j
                depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0:
                    res.append((css[start:pre_end].strip(), css[pre_end + 1:j])); j += 1; break
            j += 1
        else:
            tail = css[start:].strip()
            if tail:
                res.append((tail, None))
        i = j
    return res


def split_selectors(prelude):
    out, depth, cur = [], 0, []
    for c in prelude:
        if c in '([':
            depth += 1
        elif c in ')]':
            depth -= 1
        if c == ',' and depth == 0:
            out.append(''.join(cur)); cur = []
        else:
            cur.append(c)
    out.append(''.join(cur))
    return [s.strip() for s in out if s.strip()]


def remove_functional(sel):
    # drop the contents of :not() :is() :where() :has() :host() ::part() and [attr...] (never cause a drop)
    out, i, n = [], 0, len(sel)
    while i < n:
        m = re.match(r':{1,2}[\w-]+\(', sel[i:])
        if sel[i] == '[' or m:
            open_c = '[' if sel[i] == '[' else '('
            close_c = ']' if open_c == '[' else ')'
            j = i + (1 if open_c == '[' else len(m.group(0)))
            depth = 1
            while j < n and depth:
                if sel[j] == open_c:
                    depth += 1
                elif sel[j] == close_c:
                    depth -= 1
                j += 1
            out.append(' ')
            i = j
            continue
        out.append(sel[i]); i += 1
    return ''.join(out)


DROPPED = []
TOKEN_RE = re.compile(r'([.#])(-?[_a-zA-Z][\w-]*)')


class Corpus:
    def __init__(self, text):
        self.text = text
        self.words = set(re.findall(r'[\w-]+', text))
        # string ends that look like a class prefix: 'abc-' " abc-" `abc-${
        self.prefixes = set(m.group(1) for m in re.finditer(r'([\w-]+[-_])(?:["\'`]|\$\{)', text))
        self.cache = {}

    def has(self, tok):
        r = self.cache.get(tok)
        if r is None:
            r = tok in self.words or any(tok[:i + 1] in self.prefixes for i, c in enumerate(tok) if c in '-_' and i > 0)
            self.cache[tok] = r
        return r


def selector_possible(sel, cp):
    for _, tok in TOKEN_RE.findall(remove_functional(sel)):
        if not cp.has(tok):
            return False
    return True


def filter_css(css, cp, stats):
    out = []
    for pre, body in blocks(css):
        if body is None:
            out.append(pre + ';')
            continue
        if pre.startswith('@'):
            at = pre.split(None, 1)[0].lower()
            if at in ('@media', '@supports', '@layer', '@container', '@document'):
                inner = filter_css(body, cp, stats)
                if inner.strip():
                    out.append(pre + '{' + inner + '}')
            else:  # @font-face, @keyframes, @property, @page, @counter-style ...
                out.append(pre + '{' + body + '}')
            continue
        stats[0] += 1
        sels = split_selectors(pre)
        keep = [s for s in sels if selector_possible(s, cp)]
        if not keep:
            DROPPED.extend(sels)
        if keep:
            stats[1] += 1
            # keep the whole selector list as written: dropping a never-matching part changes nothing
            # visible, but keeping the list verbatim keeps specificity / order reviews simple
            out.append(pre + '{' + body + '}')
    return '\n'.join(out)


def build():
    files = corpus_files()
    text = read(PAGE) + '\n' + '\n'.join(read(f) for f in files)
    cp = Corpus(text)
    css = strip_comments(read(SRC))
    stats = [0, 0]
    out = HEADER + filter_css(css, cp, stats) + '\n'
    return out, stats, files


def main():
    out, stats, files = build()
    if '--check' in sys.argv:
        cur = read(OUT) if os.path.exists(OUT) else ''
        if cur != out:
            print('assets/style-charts.css is out of date: run python3 tools/build-charts-css.py')
            sys.exit(1)
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(out)
    if '--dropped' in sys.argv:  # for tools/tests/chart-css-subset-browser.js
        import json
        p = sys.argv[sys.argv.index('--dropped') + 1]
        with open(p, 'w') as f:
            json.dump(sorted(set(DROPPED)), f)
    print('rules kept %d of %d; %d KB -> %d KB; corpus %d files' % (stats[1], stats[0], os.path.getsize(SRC) // 1024, len(out.encode()) // 1024, len(files)))


if __name__ == '__main__':
    main()
