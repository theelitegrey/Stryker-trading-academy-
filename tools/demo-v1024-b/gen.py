#!/usr/bin/env python3
"""Generate demo-v1024-b.html (homepage variation B, "Editorial story").

Head links, beta strip, nav, footer and the end-of-body scripts are copied from
index.html so login/nav behave like the live home; the <main> body comes from
tools/demo-v1024-b/body.html. Unlisted: noindex,nofollow, no canonical, no OG.
Run from the repo root:  python3 tools/demo-v1024-b/gen.py
"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
idx = (root / 'index.html').read_text()
body = (root / 'tools/demo-v1024-b/body.html').read_text()
build = re.search(r'name="stryker-build" content="(\d+)"', idx).group(1)

head_end = idx.index('</head>')
head = idx[:head_end]
# drop SEO/OG bits that belong to the real home only
head = re.sub(r'<title>.*?</title>\n', '', head)
head = re.sub(r'<link rel="canonical"[^>]*>\n', '', head)
head = re.sub(r'<meta (property="og:[^"]*"|name="twitter:[^"]*"|name="description")[^>]*>\n', '', head)
head = re.sub(r'<script type="application/ld\+json">.*?</script>\n', '', head, flags=re.S)
# keep only style.css + nav-features.css from the home stylesheets
head = re.sub(r'<link rel="stylesheet" href="assets/(?!style\.css|nav-features\.css)[^"]*"[^>]*>\n', '', head)
head = re.sub(r'<link rel="preload" href="assets/images[^>]*>\n', '', head)
head = head.replace('<meta name="viewport" content="width=device-width, initial-scale=1.0">',
  '<meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
  '<!-- DEMO HOMEPAGE B "Editorial story" (Owner order 2026-10-24). Unlisted: noindex, not in nav,\n'
  '     sitemap or tools/og/pages.json. GENERATED by tools/demo-v1024-b/gen.py from\n'
  '     tools/demo-v1024-b/body.html; edit those. Styles: assets/demo-v1024-b.css. -->\n'
  '<meta name="robots" content="noindex,nofollow">\n'
  '<title>TradeZoro · See who is really buying and selling (demo B)</title>\n'
  '<meta name="description" content="Order flow, GEX levels, paper trading, replay, 64 chapters and alerts, told as a five-part story. Demo homepage.">')
head += ('<link rel="stylesheet" href="assets/demo-v1024-b.css?v=%s">\n' % build)

b0 = idx.index('\n<body>\n') + 1
m0 = idx.index('<main id="main"')
pre_main = idx[b0:m0].replace('<body>', '<body class="ed-page">', 1)
f0 = idx.index('<footer>')
f1 = idx.index('</footer>') + len('</footer>')
footer = idx[f0:f1]
scripts = idx[f1:idx.index('</body>')]
drop = ['pricing-hero.js', 'trial.js', 'home-motion.js', 'home-hero-b.js', 'home-platform-bento.js',
        'vocab-constellation.js', 'home-curriculum-bento.js', 'loading-animation.js', 'avatars.js', 'referrals.js']
for d in drop:
    scripts = re.sub(r'<script src="assets/%s\?v=\d+"[^>]*></script>\n' % re.escape(d), '', scripts)
scripts = scripts.replace('<script src="assets/theme.js',
                          '<script src="assets/demo-v1024-b.js?v=%s" defer></script>\n<script src="assets/theme.js' % build)
body = re.sub(r'\?v=\d+', '?v=' + build, body)

out = head + '</head>\n' + pre_main + body + footer + scripts + '</body>\n</html>\n'
(root / 'demo-v1024-b.html').write_text(out)
print('wrote demo-v1024-b.html, build', build, len(out), 'bytes')
