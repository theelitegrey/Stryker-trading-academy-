#!/usr/bin/env node
// Writes assets/chapters-index.js: the PUBLIC, catalog-only fallback that
// pages use when Firestore can't be reached (titles, levels, lesson titles,
// the one-paragraph teaser). The full chapter text lives in
// tools/content/chapters-data.js (never deployed; tools/ is excluded) and in
// Firestore chapterBodies/, gated by plan (see functions-src/chapterGate.js).
//
//   node tools/gen-chapters-index.js          write it
//   node tools/gen-chapters-index.js --check  exit 1 if it is out of date
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'tools', 'content', 'chapters-data.js');
const OUT = path.join(ROOT, 'assets', 'chapters-index.js');

const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(SRC, 'utf8') +
  '\n;this.__C = CHAPTERS_SEED; this.__L = LEVEL_LABEL; this.__T = LEVEL_TAG_CLASS; this.__P = PART_LABEL;', ctx);

function readMinutes(ch) {   // same estimate reader.js uses
  const strip = (h) => String(h || '').replace(/<[^>]*>/g, ' ');
  let text = strip(ch.bodyHtml) + ' ' + (ch.paragraphs || []).join(' ');
  (ch.lessons || []).forEach((l) => { text += ' ' + strip(l.descHtml || l.desc); });
  return Math.max(1, Math.round(((text.match(/\S+/g) || []).length) / 200));
}
const PLACEHOLDER = /commondatastorage\.googleapis\.com\/gtv-videos-bucket/i;
function catalogOf(ch) {
  const video = String(ch.video || '').trim();
  return {
    num: ch.num, title: ch.title, level: ch.level, dur: ch.dur || '', minRole: ch.minRole || null,
    lessons: (ch.lessons || []).map((l) => ({ title: l.title || '' })),
    preview: String((ch.paragraphs || [])[0] || '').replace(/<[^>]*>/g, ''),
    readMinutes: readMinutes(ch),
    hasVideo: !!video && !PLACEHOLDER.test(video)
  };
}
const out = '// GENERATED by tools/gen-chapters-index.js from tools/content/chapters-data.js. Do not edit.\n' +
  '// Catalog only (no chapter text): the fallback when Firestore is unreachable.\n' +
  'const CHAPTERS_SEED = ' + JSON.stringify(ctx.__C.map(catalogOf), null, 1) + ';\n\n' +
  'const LEVEL_LABEL = ' + JSON.stringify(ctx.__L) + ';\n' +
  'const LEVEL_TAG_CLASS = ' + JSON.stringify(ctx.__T) + ';\n' +
  'const PART_LABEL = ' + JSON.stringify(ctx.__P, null, 1) + ';\n';
module.exports = { catalogOf, readMinutes };
if (require.main === module) {
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('assets/chapters-index.js is stale: run node tools/gen-chapters-index.js'); process.exit(1); }
    console.log('chapters-index.js up to date');
  } else { fs.writeFileSync(OUT, out); console.log('wrote', OUT, out.length, 'bytes'); }
}
