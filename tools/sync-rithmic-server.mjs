// Copies the browser Rithmic modules into functions-src/rithmic/ as .mjs (the scheduled auto sync runs the SAME
// read-only session and grouping code). Import paths lose their ?v= cache-buster and .js becomes .mjs.
//   node tools/sync-rithmic-server.mjs          write the copies
//   node tools/sync-rithmic-server.mjs --check  exit 1 if a copy is stale (used by the tests)
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const FILES = ['rithmic-proto', 'rithmic-orders', 'rithmic-fills'];
const conv = (s) => '// GENERATED by tools/sync-rithmic-server.mjs from assets/ - do not edit here.\n' + s.replace(/(from\s+')\.\/(rithmic-[a-z]+)\.js(\?v=\d+)?(')/g, '$1./$2.mjs$4');
let stale = 0;
fs.mkdirSync(new URL('functions-src/rithmic/', root), { recursive: true });
for (const f of FILES) {
  const out = conv(fs.readFileSync(new URL('assets/' + f + '.js', root), 'utf8'));
  const dest = new URL('functions-src/rithmic/' + f + '.mjs', root);
  if (process.argv.includes('--check')) { if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out) { stale++; console.log('STALE ' + f); } }
  else fs.writeFileSync(dest, out);
}
if (stale) process.exit(1);
